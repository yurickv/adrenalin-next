type FormData = {
  fitnessGoal: string;
  gymFrequency: string;
  dietTracking: string;
  mealPlanning: string;
  mealChallenges: string[];
  autoGeneratedMenu: string;
  payForService: string;
  preferredFormat: string;
  testVersion: string;
  contact?: string;
  mealChallengesOther?: string;
  preferredFormatOther?: string;
};

function Survey() {
  const {
    register,
    handleSubmit,
    watch,
    setValue,
    getValues,
    formState: { errors, isSubmitting },
  } = useForm<FormData>({
    mode: 'onBlur',
  });
  const [submitted, setSubmitted] = useState<boolean>(() => {
    if (typeof window !== 'undefined') {
      return JSON.parse(
        sessionStorage.getItem('submittedQuestions') || 'false'
      );
    }
    return false;
  });

  useEffect(() => {
    if (typeof window !== 'undefined') {
      sessionStorage.setItem('submittedQuestions', JSON.stringify(submitted));
    }
  }, [submitted]);

  const onSubmit = async (data: FormData) => {
    if (data.mealChallenges.includes('Інше')) {
      data.mealChallenges = [
        ...data.mealChallenges,
        data.mealChallengesOther || 'Інше',
      ].filter(Boolean);
    }
    if (data.preferredFormat === 'Інше') {
      data.preferredFormat = data.preferredFormatOther || 'Інше';
    }
    try {
      const response = await fetch('/api/saveResponse', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(data),
      });
      if (response.ok) setSubmitted(true);
    } catch (error) {
      console.error('Помилка збереження:', error);
    }
  };

  return (
    <div className="min-h-[500px] p-4">
      {' '}
      <div
        className={`max-w-lg mx-auto p-6 bg-white ${
          submitted ? '' : 'shadow-lg rounded-lg'
        } my-8 text-center`}
      >
        {submitted ? (
          <>
            <h2 className="text-center text-green-600 text-lg font-semibold h-fit my-10">
              Дякуємо за участь!
            </h2>
            <Link
              href="#"
              className="p-2 rounded mt-4 shadow-md"
              onClick={e => {
                e.preventDefault();
                history.back();
              }}
            >
              Повернутись назад
            </Link>
          </>
        ) : (
          <form onSubmit={handleSubmit(onSubmit)} className="space-y-6">
            {Object.entries(surveyQuestions).map(
              ([key, { label, options }]) => (
                <div key={key}>
                  <h2 className="text-xl font-bold">🔹 {label}</h2>
                  <div className="flex flex-col space-y-2">
                    {options.map(option => (
                      <label key={option} className="flex items-center">
                        <input
                          type={key === 'mealChallenges' ? 'checkbox' : 'radio'}
                          {...register(key as keyof FormData, {
                            required: "Це поле є обов'язковим",
                          })}
                          value={option}
                          className="mr-2"
                        />
                        {option}
                      </label>
                    ))}
                    {(() => {
                      const watchValue = watch(key as keyof FormData);
                      // Check if the watchValue is an array or a string and handle accordingly
                      if (
                        Array.isArray(watchValue) &&
                        watchValue.includes('Інше')
                      ) {
                        return (
                          <input
                            type="text"
                            {...register(`${key}Other` as keyof FormData, {
                              maxLength: 100,
                            })}
                            className="w-full border p-2 rounded"
                            placeholder="Введіть свій варіант"
                          />
                        );
                      }
                      if (watchValue === 'Інше') {
                        return (
                          <input
                            type="text"
                            {...register(`${key}Other` as keyof FormData, {
                              maxLength: 100,
                            })}
                            className="w-full border p-2 rounded"
                            placeholder="Введіть свій варіант"
                          />
                        );
                      }
                      return null;
                    })()}
                  </div>
                  {errors[key as keyof FormData] && (
                    <p className="text-red-600 text-sm">
                      {errors[key as keyof FormData]?.message}
                    </p>
                  )}
                </div>
              )
            )}
            {watch('testVersion') === 'Так, залишаю контакт' && (
              <div>
                <input
                  type="text"
                  placeholder="Номер телефону"
                  {...register('contact', {
                    pattern: {
                      value: /^\+?\d{10,15}$/,
                      message: 'Невірний формат номеру телефону',
                    },
                    required: "Це поле є обов'язковим",
                  })}
                  className="w-full border p-2 rounded"
                />
                {errors.contact && (
                  <p className="text-red-600 text-sm">
                    {errors.contact?.message}
                  </p>
                )}
              </div>
            )}
            <button
              type="submit"
              disabled={isSubmitting}
              className={`w-full text-mainTitle rounded-xl p-4 flex gap-4 justify-center ${
                isSubmitting
                  ? 'bg-orange-50'
                  : 'bg-orange-100 hover:bg-orange-200 dark:bg-[#a3a3a3] dark:hover:bg-[#d4d4d4]'
              }`}
            >
              <span
                className={`${isSubmitting ? 'block animate-spin' : 'hidden'}`}
              >
                &#10227;
              </span>
              Надіслати
            </button>
          </form>
        )}
      </div>
    </div>
  );
}

export default Survey;
